// crypto.randomUUID only exists in secure contexts (HTTPS or localhost), so opening the
// app over plain HTTP on a network address (e.g. a phone on the LAN) would break every
// add. getRandomValues works everywhere, so build a v4 UUID from it as a fallback.
export function uid() {
  if (typeof crypto.randomUUID === 'function') return crypto.randomUUID();
  const b = crypto.getRandomValues(new Uint8Array(16));
  b[6] = (b[6] & 0x0f) | 0x40;
  b[8] = (b[8] & 0x3f) | 0x80;
  const hex = [...b].map((x) => x.toString(16).padStart(2, '0')).join('');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}
